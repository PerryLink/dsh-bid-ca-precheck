#!/usr/bin/env node
/**
 * Adapt World Bank procurement notices into the material shape dsh-bid-ca-precheck reads.
 *
 * The notices are **requirements-side** public data. This adapter:
 *   1. selects a deterministic, construction-related sample of Invitation for Bids;
 *   2. writes a requirements pack containing only fields present in the API response;
 *   3. writes clean synthetic bid-response registers (one notice per clean case);
 *   4. injects the register defects the shipped rule pack can detect;
 *   5. writes explicit blind-spot probes for mismatches the pack has no rule for;
 *   6. generates the benchmark-local rule-pack overlay that fills BC-002's verdict
 *      vocabulary and BC-005's high-risk keywords, which ship empty by design.
 *
 * Every bid-side value is synthetic and labelled as such. No real bidder, response,
 * verdict or evidence document is claimed.
 *
 * Usage:
 *   node bench/public-worldbank/adapter.mjs
 *   node bench/public-worldbank/adapter.mjs --limit 8
 *
 * Prerequisite: fetch.mjs has written .data/wb-procnotices.construction.json and
 * its .meta.json sidecar.
 */

