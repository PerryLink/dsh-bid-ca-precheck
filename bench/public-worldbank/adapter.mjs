function parseArgs(argv) {
  const options = {
    raw: DEFAULT_RAW,
    outDir: DATA_DIR,
    limit: 8,
  }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--help' || argument === '-h') {
      usage()
      process.exit(0)
    }
    if (!argument.startsWith('--')) throw new Error(`unknown argument: ${argument}`)
    const equals = argument.indexOf('=')
    const name = equals === -1 ? argument : argument.slice(0, equals)
    const inline = equals === -1 ? undefined : argument.slice(equals + 1)
    const value = inline ?? argv[(index += 1)]
    if (value === undefined) throw new Error(`missing value for ${name}`)
    switch (name) {
      case '--raw':
        options.raw = isAbsolute(value) ? value : resolve(process.cwd(), value)
        break
      case '--out-dir':
        options.outDir = isAbsolute(value) ? value : resolve(process.cwd(), value)
        break
      case '--limit':
        options.limit = Number.parseInt(value, 10)
        break
      default:
        throw new Error(`unknown argument: ${name}`)
    }
  }
  if (!Number.isInteger(options.limit) || options.limit < 4 || options.limit > 50) {
    throw new Error('--limit must be an integer from 4 to 50')
  }
  return options
}

function sha256(text) {
  return createHash('sha256').update(text).digest('hex')
}

function relativeToRepo(path) {
  return path.startsWith(REPO_ROOT) ? path.slice(REPO_ROOT.length + 1).replaceAll('\\', '/') : path
}

function assert(condition, message) {
  if (!condition) throw new Error(message)
}

async function readJson(path) {
  return JSON.parse(await readFile(path, 'utf8'))
}

function nonEmptyString(value) {
  return typeof value === 'string' && value.trim() !== ''
}

function countOccurrences(text, needle) {
  return text.split(needle).length - 1
}

function slug(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 52)
}

function clone(value) {
  return structuredClone(value)
}

function addDays(iso, days) {
  const date = new Date(iso)
  assert(!Number.isNaN(date.getTime()), `cannot add days to an unparseable date: ${iso}`)
  date.setUTCDate(date.getUTCDate() + days)
  return date.toISOString()
}

/** Make a clause value differ only by whitespace, to exercise BC-003's normalisation. */
function withInternalSpace(value) {
  const hyphen = value.indexOf('-')
  if (hyphen >= 0) return `${value.slice(0, hyphen + 1)} ${value.slice(hyphen + 1)}`
  return `${value.slice(0, 2)} ${value.slice(2)}`
}

/**
 * Keep only notices that carry every field this bench consumes and that are
 * construction-related Invitation for Bids with a parseable deadline.
 * Rejections are counted, never silently dropped.
 */
function filterCandidates(notices) {
  const stats = {
    input: notices.length,
    notObject: 0,
    notInvitationForBids: 0,
    missingDeadline: 0,
    unparseableDeadline: 0,
    missingReference: 0,
    missingDescription: 0,
    missingCountry: 0,
    missingMethod: 0,
    notConstruction: 0,
    noHighRiskKeyword: 0,
    placeholder: 0,
    duplicateReference: 0,
    accepted: 0,
  }
  const seenReferences = new Set()
  const candidates = []

  for (const notice of notices) {
    if (notice === null || typeof notice !== 'object' || Array.isArray(notice)) {
      stats.notObject += 1
      continue
    }
    if (notice.notice_type !== 'Invitation for Bids') {
      stats.notInvitationForBids += 1
      continue
    }
    if (!nonEmptyString(notice.submission_deadline_date)) {
      stats.missingDeadline += 1
      continue
    }
    if (Number.isNaN(Date.parse(notice.submission_deadline_date))) {
      stats.unparseableDeadline += 1
      continue
    }
    if (!nonEmptyString(notice.bid_reference_no)) {
      stats.missingReference += 1
      continue
    }
    if (!nonEmptyString(notice.bid_description)) {
      stats.missingDescription += 1
      continue
    }
    if (!nonEmptyString(notice.project_ctry_name)) {
      stats.missingCountry += 1
      continue
    }
    if (!nonEmptyString(notice.procurement_method_name)) {
      stats.missingMethod += 1
      continue
    }

    const description = notice.bid_description
    if (!/construct/i.test(description)) {
      stats.notConstruction += 1
      continue
    }
    if (!HIGH_RISK_KEYWORDS.some((keyword) => description.includes(keyword))) {
      stats.noHighRiskKeyword += 1
      continue
    }
    if (PLACEHOLDER_TERMS.some((term) => description.includes(term))) {
      stats.placeholder += 1
      continue
    }

    const reference = notice.bid_reference_no.trim()
    if (seenReferences.has(reference)) {
      stats.duplicateReference += 1
      continue
    }
    seenReferences.add(reference)
    candidates.push(notice)
  }

  stats.accepted = candidates.length
  return { candidates, stats }
}

/**
 * Pick one notice per country in the first pass, then fill from the remaining
 * candidates. Both the group order and the within-group order are sorted, so the
 * selection does not depend on the API's result order.
 */
function selectCandidates(candidates, limit) {
  const sorted = [...candidates].sort(
    (left, right) =>
      left.project_ctry_name.localeCompare(right.project_ctry_name) ||
      left.bid_reference_no.localeCompare(right.bid_reference_no),
  )
  const groups = new Map()
  for (const notice of sorted) {
    const country = notice.project_ctry_name
    if (!groups.has(country)) groups.set(country, [])
    groups.get(country).push(notice)
  }
  const countries = [...groups.keys()].sort()
  const selected = []
  const used = new Set()

  while (selected.length < limit) {
    let added = false
    for (const country of countries) {
      if (selected.length >= limit) break
      const next = groups.get(country).find((notice) => !used.has(notice.bid_reference_no))
      if (next === undefined) continue
      selected.push(next)
      used.add(next.bid_reference_no)
      added = true
    }
    if (!added) break
  }
  for (const notice of sorted) {
    if (selected.length >= limit) break
    if (used.has(notice.bid_reference_no)) continue
    selected.push(notice)
    used.add(notice.bid_reference_no)
  }

  selected.sort(
    (left, right) =>
      left.project_ctry_name.localeCompare(right.project_ctry_name) ||
      left.bid_reference_no.localeCompare(right.bid_reference_no),
  )
  return selected
}

/** Project only fields that exist in the API response. */
function projectNotice(notice) {
  const projected = {
    bid_reference_no: notice.bid_reference_no,
    notice_type: notice.notice_type,
    submission_deadline_date: notice.submission_deadline_date,
    project_ctry_name: notice.project_ctry_name,
    bid_description: notice.bid_description,
    procurement_method_name: notice.procurement_method_name,
  }
  if (nonEmptyString(notice.project_name)) projected.project_name = notice.project_name
  if (nonEmptyString(notice.id)) projected.notice_id = notice.id
  return projected
}

function cleanRow(notice) {
  return {
    clause: notice.bid_reference_no,
    requirement: notice.bid_description,
    response: SYNTHETIC.response,
    verdict: SYNTHETIC.verdict,
    evidence: SYNTHETIC.evidence,
    notice_type: notice.notice_type,
    submission_deadline_date: notice.submission_deadline_date,
    procurement_method_name: notice.procurement_method_name,
    project_ctry_name: notice.project_ctry_name,
    note: SYNTHETIC.note,
  }
}

function cleanBid(notice) {
  return {
    project: nonEmptyString(notice.project_name) ? notice.project_name : notice.project_ctry_name,
    tenderNo: notice.bid_reference_no,
    bidder: SYNTHETIC.bidder,
    rows: [cleanRow(notice)],
  }
}

function withRow(bid, index, patch) {
  const next = clone(bid)
  next.rows[index] = { ...next.rows[index], ...patch }
  return next
}

function withExtraRow(bid, row) {
  const next = clone(bid)
  next.rows.push(row)
  return next
}

function withoutHeader(bid, field) {
  const next = clone(bid)
  delete next[field]
  return next
}

function makeCase(input) {
  assert(/^[a-z0-9-]+$/.test(input.id), `case id must be lower-case kebab: ${input.id}`)
  assert(['clean', 'mutation', 'blind-spot'].includes(input.kind), `bad case kind: ${input.kind}`)
  assert(Array.isArray(input.requirements) && input.requirements.length > 0, `${input.id}: requirements required`)
  assert(input.bid !== null && typeof input.bid === 'object', `${input.id}: bid object required`)
  assert(Array.isArray(input.bid.rows) && input.bid.rows.length > 0, `${input.id}: bid.rows required`)
  assert(nonEmptyString(input.description), `${input.id}: description required`)

  const expected = {}
  for (const [rule, count] of Object.entries(input.expected ?? {})) {
    assert(RULES.includes(rule), `${input.id}: unknown rule ${rule}`)
    assert(Number.isInteger(count) && count >= 0, `${input.id}: expected count must be a non-negative integer`)
    if (count > 0) expected[rule] = count
  }
  if (input.kind === 'mutation') {
    assert(RULES.includes(input.targetRule), `${input.id}: mutation needs a target rule`)
    assert(expected[input.targetRule] === 1, `${input.id}: mutation must expect exactly one hit of ${input.targetRule}`)
  } else {
    assert(Object.keys(expected).length === 0, `${input.id}: ${input.kind} case must not expect issues`)
  }

  return {
    id: input.id,
    kind: input.kind,
    targetRule: input.targetRule ?? null,
    description: input.description,
    requirements: input.requirements,
    bid: input.bid,
    expected,
    ...(input.blindSpot === undefined ? {} : { blindSpot: input.blindSpot }),
  }
}

function mutationCase({ id, targetRule, description, notice, bid }) {
  return makeCase({
    id,
    kind: 'mutation',
    targetRule,
    description,
    requirements: [projectNotice(notice)],
    bid,
    expected: { [targetRule]: 1 },
  })
}

function blindSpotCase({ id, description, requirements, bid, blindSpot }) {
  return makeCase({
    id,
    kind: 'blind-spot',
    targetRule: null,
    description,
    requirements,
    bid,
    expected: {},
    blindSpot,
  })
}

function buildCases(selected) {
  assert(selected.length >= 4, 'need at least 4 selected notices to build the case set')
  const [first, second, third, fourth] = selected

  const cleanCases = selected.map((notice, index) =>
    makeCase({
      id: `clean-${String(index + 1).padStart(2, '0')}-${slug(notice.bid_reference_no)}`,
      kind: 'clean',
      targetRule: null,
      description:
        `Clean synthetic register for ${notice.bid_reference_no} (${notice.project_ctry_name}); ` +
        'the response, verdict and evidence cells are synthetic placeholders, not bidder claims.',
      requirements: [projectNotice(notice)],
      bid: cleanBid(notice),
      expected: {},
    }),
  )

  const mutations = [
    mutationCase({
      id: 'bc001-missing-response-a',
      targetRule: 'BC-001',
      description: 'Clean register with the response cell blank on one notice (requirement present, response missing).',
      notice: first,
      bid: withRow(cleanBid(first), 0, { response: '' }),
    }),
    mutationCase({
      id: 'bc001-missing-response-b',
      targetRule: 'BC-001',
      description: 'Clean register with the response cell blank on a second notice.',
      notice: second,
      bid: withRow(cleanBid(second), 0, { response: '' }),
    }),
    mutationCase({
      id: 'bc002-off-vocabulary-a',
      targetRule: 'BC-002',
      description: 'Verdict changed to a value outside the benchmark-local vocabulary (only executed by the configured overlay).',
      notice: first,
      bid: withRow(cleanBid(first), 0, { verdict: 'SYNTHETIC_OFF_VOCAB' }),
    }),
    mutationCase({
      id: 'bc002-off-vocabulary-b',
      targetRule: 'BC-002',
      description: 'Second notice carries an off-vocabulary verdict.',
      notice: third,
      bid: withRow(cleanBid(third), 0, { verdict: 'SYNTHETIC_OFF_VOCAB' }),
    }),
    mutationCase({
      id: 'bc003-duplicate-clause-exact',
      targetRule: 'BC-003',
      description: 'The same notice is registered twice with the same clause number.',
      notice: first,
      bid: withExtraRow(cleanBid(first), clone(cleanRow(first))),
    }),
    mutationCase({
      id: 'bc003-duplicate-clause-whitespace',
      targetRule: 'BC-003',
      description: 'A clause number repeats after BC-003 removes whitespace; the values differ only by an internal space.',
      notice: second,
      bid: withExtraRow(
        cleanBid(second),
        { ...clone(cleanRow(second)), clause: withInternalSpace(second.bid_reference_no) },
      ),
    }),
    mutationCase({
      id: 'bc004-missing-project',
      targetRule: 'BC-004',
      description: 'Register header omits the project name; the bidder remains.',
      notice: first,
      bid: withoutHeader(cleanBid(first), 'project'),
    }),
    mutationCase({
      id: 'bc004-missing-bidder',
      targetRule: 'BC-004',
      description: 'Register header omits the bidder; the project remains.',
      notice: second,
      bid: withoutHeader(cleanBid(second), 'bidder'),
    }),
    mutationCase({
      id: 'bc004-missing-both',
      targetRule: 'BC-004',
      description: 'Register header omits both project and bidder; BC-004 reports one header finding, not two.',
      notice: third,
      bid: withoutHeader(withoutHeader(cleanBid(third), 'project'), 'bidder'),
    }),
    mutationCase({
      id: 'bc005-missing-evidence-a',
      targetRule: 'BC-005',
      description: 'A high-risk requirement carries a blank evidence cell (only executed by the configured overlay).',
      notice: first,
      bid: withRow(cleanBid(first), 0, { evidence: '' }),
    }),
    mutationCase({
      id: 'bc005-missing-evidence-b',
      targetRule: 'BC-005',
      description: 'A second high-risk requirement carries a blank evidence cell.',
      notice: fourth,
      bid: withRow(cleanBid(fourth), 0, { evidence: '' }),
    }),
    mutationCase({
      id: 'bc006-placeholder-double-brace',
      targetRule: 'BC-006',
      description: 'The requirement column keeps a {{TBD}} template placeholder.',
      notice: first,
      bid: withRow(cleanBid(first), 0, { requirement: `${first.bid_description} {{TBD}}` }),
    }),
    mutationCase({
      id: 'bc006-placeholder-cjk-bracket',
      targetRule: 'BC-006',
      description: 'The requirement column keeps a 【待填】 placeholder.',
      notice: second,
      bid: withRow(cleanBid(second), 0, { requirement: `${second.bid_description} 【待填】` }),
    }),
    mutationCase({
      id: 'bc006-placeholder-xxx',
      targetRule: 'BC-006',
      description: 'The requirement column keeps an XXX placeholder.',
      notice: third,
      bid: withRow(cleanBid(third), 0, { requirement: `${third.bid_description} XXX` }),
    }),
  ]

  const wrongDeadline = addDays(first.submission_deadline_date, 1)
  const blindSpots = [
    blindSpotCase({
      id: 'blind-wrong-deadline',
      description: 'The bid-side deadline differs from the notice by one day; the register is otherwise clean.',
      requirements: [projectNotice(first)],
      bid: withRow(cleanBid(first), 0, {
        submission_deadline_date: wrongDeadline,
        note: `${SYNTHETIC.note} Injected mismatch: submission deadline moved by +1 day.`,
      }),
      blindSpot: {
        kind: 'wrong-deadline',
        field: 'submission_deadline_date',
        requirementValue: first.submission_deadline_date,
        bidValue: wrongDeadline,
        why:
          'The six-rule pack has no deadline check and no rule compares a bid row against the notice. ' +
          'The register columns it reads are clause, requirement, response, verdict, evidence and header.',
      },
    }),
    blindSpotCase({
      id: 'blind-wrong-notice-type',
      description: 'The bid-side notice type is Contract Award while the notice is Invitation for Bids.',
      requirements: [projectNotice(first)],
      bid: withRow(cleanBid(first), 0, {
        notice_type: 'Contract Award',
        note: `${SYNTHETIC.note} Injected mismatch: notice type changed.`,
      }),
      blindSpot: {
        kind: 'wrong-notice-type',
        field: 'notice_type',
        requirementValue: first.notice_type,
        bidValue: 'Contract Award',
        why:
          'The six-rule pack has no notice-type check. ' +
          'Neither BC-001 nor BC-004 reads notice_type; the value is retained by the reader but no rule consumes it.',
      },
    }),
    blindSpotCase({
      id: 'blind-extra-bid-row',
      description: 'The bid carries an extra row whose clause is absent from the requirements pack.',
      requirements: [projectNotice(first)],
      bid: withExtraRow(cleanBid(first), {
        clause: 'SYNTHETIC-PHANTOM-NOT-IN-REQUIREMENTS',
        requirement: 'SYNTHETIC phantom requirement for a benchmark control; this is not a World Bank notice.',
        response: SYNTHETIC.response,
        verdict: SYNTHETIC.verdict,
        evidence: SYNTHETIC.evidence,
        note: 'Synthetic control row deliberately absent from the requirements pack.',
      }),
      blindSpot: {
        kind: 'extra-bid-row',
        field: 'clause',
        requirementValue: null,
        bidValue: 'SYNTHETIC-PHANTOM-NOT-IN-REQUIREMENTS',
        why:
          'The plugin checks the register it is given; it has no reference set and no referential-integrity rule. ' +
          'It cannot know that a clause is absent from the requirements pack.',
      },
    }),
    blindSpotCase({
      id: 'blind-missing-bid-row',
      description: 'A requirement in the pack has no corresponding bid row; the bid register has only the other notice.',
      requirements: [projectNotice(first), projectNotice(second)],
      bid: cleanBid(first),
      blindSpot: {
        kind: 'missing-bid-row',
        field: 'clause',
        requirementValue: second.bid_reference_no,
        bidValue: null,
        why:
          'BC-001 checks rows that are present; it cannot report a row that was never in the material. ' +
          'No rule compares the register against an external requirements pack.',
      },
    }),
  ]

  const cases = [...cleanCases, ...mutations, ...blindSpots]
  const ids = new Set()
  for (const item of cases) {
    assert(!ids.has(item.id), `duplicate case id: ${item.id}`)
    ids.add(item.id)
  }
  return cases
}

function buildRequirementsDocument({ fetchMeta, selected, limit }) {
  return {
    schemaVersion: 1,
    benchmark: 'public-worldbank',
    generatedAt: new Date().toISOString(),
    plugin: 'dsh-bid-ca-precheck',
    source: {
      publisher: DATASET.publisher,
      dataset: DATASET,
      endpoint: fetchMeta.endpoint,
      retrievedAt: fetchMeta.retrievedAt,
      rawSha256: fetchMeta.sha256,
      api: fetchMeta.api,
    },
    license: DATASET,
    selection: {
      filter: {
        notice_type: 'Invitation for Bids',
        submission_deadline_date: 'present and parseable',
        required_fields: [
          'bid_reference_no',
          'notice_type',
          'submission_deadline_date',
          'project_ctry_name',
          'bid_description',
          'procurement_method_name',
        ],
        construction_related: 'bid_description contains "construct" (case-insensitive)',
        high_risk_keyword: HIGH_RISK_KEYWORDS,
        placeholder_free: true,
      },
      algorithm:
        'sort by project_ctry_name then bid_reference_no; one notice per country in a first round, ' +
        'then fill from the remaining sorted candidates; sort the final selection the same way',
      requested: limit,
      selected: selected.length,
      countries: [...new Set(selected.map((notice) => notice.project_ctry_name))].sort(),
    },
    syntheticBid: {
      warning:
        'The notices are requirements-side public data. Everything on the bid side is synthetic: ' +
        'bidder name, responses, verdicts, evidence placeholders and case mutations. ' +
        'No real bidder, bid submission or compliance outcome is claimed.',
      bidder: SYNTHETIC.bidder,
      response: SYNTHETIC.response,
      verdict: SYNTHETIC.verdict,
      evidence: SYNTHETIC.evidence,
    },
    notices: selected.map(projectNotice),
  }
}

function buildCasesDocument({ cases, shippedVersion, configuredVersion }) {
  return {
    schemaVersion: 1,
    benchmark: 'public-worldbank',
    generatedAt: new Date().toISOString(),
    plugin: 'dsh-bid-ca-precheck',
    rules: RULES,
    defaultScoredRules: DEFAULT_SCORED_RULES,
    rulesets: {
      shippedVersion,
      configuredVersion,
      overlayFills: {
        'BC-002': { values: VERDICT_VOCABULARY },
        'BC-005': { highRiskKeywords: HIGH_RISK_KEYWORDS },
      },
    },
    counts: {
      total: cases.length,
      clean: cases.filter((item) => item.kind === 'clean').length,
      mutation: cases.filter((item) => item.kind === 'mutation').length,
      blindSpot: cases.filter((item) => item.kind === 'blind-spot').length,
    },
    cases,
  }
}

async function main() {
  const options = parseArgs(process.argv.slice(2))
  const rawPath = options.raw
  const metaPath = `${rawPath.replace(/\.json$/i, '')}.meta.json`
  const outDir = options.outDir
  const casesDir = resolve(outDir, 'cases')
  const requirementsPath = resolve(outDir, 'requirements.json')
  const casesPath = resolve(outDir, 'cases.json')
  const overlayPath = resolve(outDir, 'rules-configured.yaml')
  const adapterMetaPath = resolve(outDir, 'adapter-meta.json')
  const shippedRulesPath = resolve(REPO_ROOT, 'rules/bid-ca-precheck.yaml')

  const rawText = await readFile(rawPath, 'utf8')
  const rawMeta = await readJson(metaPath)
  assert(
    rawMeta.sha256 === sha256(rawText),
    `fetch metadata hash does not match ${rawPath}; re-run fetch.mjs instead of editing the raw file`,
  )
  const api = JSON.parse(rawText)
  assert(Array.isArray(api.procnotices), 'raw response has no procnotices array')

  const { candidates, stats } = filterCandidates(api.procnotices)
  const selected = selectCandidates(candidates, options.limit)
  assert(
    selected.length === options.limit,
    `only ${selected.length} notice(s) matched the selection filter; need ${options.limit}. ` +
      'Increase --rows in fetch.mjs or lower --limit (minimum 4).',
  )

  const cases = buildCases(selected)

  const shippedRules = await readFile(shippedRulesPath, 'utf8')
  const versionLine = /^version:\s*".*"$/m.exec(shippedRules)?.[0]
  const shippedVersion = /^version:\s*"([^"]+)"/m.exec(shippedRules)?.[1]
  assert(versionLine !== undefined && shippedVersion !== undefined, `no version line in ${shippedRulesPath}`)
  const configuredVersion = `${shippedVersion}-bench-configured`

  const valuesToken = '        values: []'
  const highRiskToken = '      highRiskKeywords: []'
  assert(
    countOccurrences(shippedRules, valuesToken) === 1,
    `expected exactly one "${valuesToken.trim()}" in the shipped rule pack`,
  )
  assert(
    countOccurrences(shippedRules, highRiskToken) === 1,
    `expected exactly one "${highRiskToken.trim()}" in the shipped rule pack`,
  )

  let overlay = shippedRules
  overlay = overlay.replace(valuesToken, `        values: [${VERDICT_VOCABULARY.map((value) => JSON.stringify(value)).join(', ')}]`)
  overlay = overlay.replace(
    highRiskToken,
    `      highRiskKeywords: [${HIGH_RISK_KEYWORDS.map((value) => JSON.stringify(value)).join(', ')}]`,
  )
  overlay = overlay.replace(versionLine, `version: "${configuredVersion}"`)
  overlay = [
    '# BENCHMARK OVERLAY — generated by bench/public-worldbank/adapter.mjs.',
    '# Same six rules as rules/bid-ca-precheck.yaml; only the two institution-local',
    '# lists (BC-002 values, BC-005 highRiskKeywords) are filled so those rules can',
    '# execute. This file is generated into .data/ and is not a plugin release artifact.',
    '',
    overlay,
  ].join('\n')
  assert(overlay.includes('version: "' + configuredVersion + '"'), 'overlay version replacement failed')
  assert(!overlay.includes(valuesToken), 'overlay still has the empty BC-002 values list')
  assert(!overlay.includes(highRiskToken), 'overlay still has the empty BC-005 highRiskKeywords list')

  const requirementsDocument = buildRequirementsDocument({ fetchMeta: rawMeta, selected, limit: options.limit })
  const casesDocument = buildCasesDocument({ cases, shippedVersion, configuredVersion })

  const requirementsBody = `${JSON.stringify(requirementsDocument, null, 2)}\n`
  const casesBody = `${JSON.stringify(casesDocument, null, 2)}\n`
  const overlayBody = `${overlay.trimEnd()}\n`

  await mkdir(casesDir, { recursive: true })
  await writeFile(requirementsPath, requirementsBody, 'utf8')
  await writeFile(casesPath, casesBody, 'utf8')
  await writeFile(overlayPath, overlayBody, 'utf8')
  for (const item of cases) {
    await writeFile(resolve(casesDir, `${item.id}.json`), `${JSON.stringify(item, null, 2)}\n`, 'utf8')
    await writeFile(resolve(casesDir, `${item.id}.bid.json`), `${JSON.stringify(item.bid, null, 2)}\n`, 'utf8')
  }

  const byTargetRule = {}
  for (const item of cases) {
    if (item.targetRule === null) continue
    byTargetRule[item.targetRule] = (byTargetRule[item.targetRule] ?? 0) + 1
  }

  const adapterMeta = {
    schemaVersion: 1,
    benchmark: 'public-worldbank',
    generatedAt: new Date().toISOString(),
    plugin: 'dsh-bid-ca-precheck',
    source: {
      publisher: DATASET.publisher,
      dataset: DATASET,
      endpoint: rawMeta.endpoint,
      retrievedAt: rawMeta.retrievedAt,
      raw: relativeToRepo(rawPath),
      rawMeta: relativeToRepo(metaPath),
      rawSha256: rawMeta.sha256,
      api: rawMeta.api,
    },
    license: DATASET,
    selection: {
      requested: options.limit,
      selected: selected.length,
      countries: [...new Set(selected.map((notice) => notice.project_ctry_name))].sort(),
      notices: selected.map(projectNotice),
      candidateStats: stats,
    },
    cases: {
      total: cases.length,
      clean: cases.filter((item) => item.kind === 'clean').length,
      mutation: cases.filter((item) => item.kind === 'mutation').length,
      blindSpot: cases.filter((item) => item.kind === 'blind-spot').length,
      byTargetRule,
      ids: cases.map((item) => item.id),
    },
    rulesets: {
      shippedVersion,
      configuredVersion,
      overlayFills: {
        'BC-002': { values: VERDICT_VOCABULARY },
        'BC-005': { highRiskKeywords: HIGH_RISK_KEYWORDS },
      },
    },
    files: {
      raw: relativeToRepo(rawPath),
      rawMeta: relativeToRepo(metaPath),
      requirements: relativeToRepo(requirementsPath),
      cases: relativeToRepo(casesPath),
      casesDir: relativeToRepo(casesDir),
      overlay: relativeToRepo(overlayPath),
      adapterMeta: relativeToRepo(adapterMetaPath),
    },
    hashes: {
      raw: rawMeta.sha256,
      requirements: sha256(requirementsBody),
      cases: sha256(casesBody),
      overlay: sha256(overlayBody),
    },
  }
  const adapterMetaBody = `${JSON.stringify(adapterMeta, null, 2)}\n`
  await writeFile(adapterMetaPath, adapterMetaBody, 'utf8')

  console.log(
    `wb adapter: ${selected.length}/${options.limit} clean notices selected from ${stats.input} API rows ` +
      `(${stats.accepted} candidate(s) passed the filter)`,
  )
  console.log(
    `  filter rejects: IFB=${stats.notInvitationForBids} deadline=${stats.missingDeadline + stats.unparseableDeadline} ` +
      `construction=${stats.notConstruction} keyword=${stats.noHighRiskKeyword} placeholder=${stats.placeholder} ` +
      `duplicate-ref=${stats.duplicateReference}`,
  )
  console.log(`  countries: ${adapterMeta.selection.countries.join(', ')}`)
  console.log(`  requirements: ${relativeToRepo(requirementsPath)}`)
  console.log(
    `  cases: ${cases.length} (${adapterMeta.cases.clean} clean, ${adapterMeta.cases.mutation} mutation, ` +
      `${adapterMeta.cases.blindSpot} blind-spot)`,
  )
  console.log(`  configured rule overlay: ${relativeToRepo(overlayPath)} (${configuredVersion})`)
  console.log(`  hashes: raw=${rawMeta.sha256.slice(0, 16)}… cases=${adapterMeta.hashes.cases.slice(0, 16)}…`)
}

main().catch((error) => {
  console.error(error instanceof Error ? error.stack ?? error.message : String(error))
  process.exitCode = 1
})
