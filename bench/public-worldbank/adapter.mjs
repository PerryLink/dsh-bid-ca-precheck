const DEFAULT_RAW = resolve(DATA_DIR, 'wb-procnotices.construction.json')

const RULES = ['BC-001', 'BC-002', 'BC-003', 'BC-004', 'BC-005', 'BC-006']
const DEFAULT_SCORED_RULES = ['BC-001', 'BC-003', 'BC-004', 'BC-006']
const HIGH_RISK_KEYWORDS = ['Construction', 'construction', 'CONSTRUCTION']
const VERDICT_VOCABULARY = ['SYNTHETIC_ACK']
const PLACEHOLDER_TERMS = ['【', '】', '{{', '}}', 'XXX', 'xxx', '待填', '待补充', 'TBD', 'todo']

